-- ============================================================================
-- 0017 — מיקום פרסום חדש: ריבוע בסיידבר של עמוד הבית
--
-- עד כה היו שני מיקומים בלבד (side_start / side_end), שניהם באנרים
-- צדדיים צרים שמוצגים רק ממסכים רחבים. הריבוע שמתחת ל"מדריכים
-- מומלצים" הוא מיקום אחר לגמרי: הוא בתוך זרימת התוכן, מוצג בכל
-- רוחב מסך, והיחס שלו מרובע ולא אנכי-צר.
--
-- מיקום נפרד ולא שימוש חוזר ב-side_start: לבאנר יש ממדים מומלצים
-- שמוצגים למנהל במסך ההעלאה, ושליחת קריאייטיב של 160x500 לתוך
-- ריבוע 300x250 מייצרת בדיוק את התמונה המעוותת שהעמודה ההיא
-- נועדה למנוע.
-- ============================================================================

insert into public.ad_placements (key, label, description, width, height) values
  ('home_sidebar', 'ריבוע — סיידבר עמוד הבית',
   'מתחת ל"מדריכים מומלצים". מוצג בכל רוחב מסך. יחס מרובע.', 300, 250)
on conflict (key) do update
  set label       = excluded.label,
      description = excluded.description,
      width       = excluded.width,
      height      = excluded.height;
